import pandas as pd

# ==================================================
# Задание 1.1: Два набора с одинаковым средним (50)
# ==================================================
# Плотный набор: значения близки к 50
dense = [48, 49, 50, 50, 51, 52]      # среднее = (48+49+50+50+51+52)/6 = 300/6 = 50
# Широкий набор: большой разброс
wide = [10, 30, 50, 50, 70, 90]       # среднее = (10+30+50+50+70+90)/6 = 300/6 = 50

dense_series = pd.Series(dense)
wide_series = pd.Series(wide)

print("Плотный набор (dense):", dense)
print("  min =", dense_series.min(), ", max =", dense_series.max(), ", mean =", dense_series.mean())
print("Широкий набор (wide):", wide)
print("  min =", wide_series.min(), ", max =", wide_series.max(), ", mean =", wide_series.mean())

