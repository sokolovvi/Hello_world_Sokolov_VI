import pandas as pd
import numpy as np

# ==================================================
# Задание 1: Перцентильный ранг оценки
# ==================================================
np.random.seed(42)
# Создаём Series из 15 случайных оценок от 30 до 100
scores = pd.Series(np.random.randint(30, 101, 15))
your_score = 70

print("Оценки студентов:", scores.values)
print(f"Ваша оценка: {your_score}")

# Вычисляем перцентильный ранг: доля оценок <= your_score, умноженная на 100
percentile_rank = (scores <= your_score).mean() * 100
print(f"Перцентильный ранг оценки {your_score}: {percentile_rank:.1f}")

