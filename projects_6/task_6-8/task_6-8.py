import pandas as pd
import numpy as np

# ==================================================
# Задание 1.1: Выборочная дисперсия вручную
# ==================================================
print("=== Задание 1.1 ===")
data = [4, 8, 6, 5, 3, 7, 9, 5]
n = len(data)

# Шаг 1: Найти среднее арифметическое
mean = sum(data) / n
print(f"Шаг 1: среднее = {mean}")

# Шаг 2: Вычислить отклонения каждого значения от среднего
deviations = [x - mean for x in data]
print(f"Шаг 2: отклонения = {deviations}")

# Шаг 3: Возвести каждое отклонение в квадрат
squared_deviations = [d**2 for d in deviations]
print(f"Шаг 3: квадраты отклонений = {squared_deviations}")

# Шаг 4: Найти сумму квадратов отклонений
sum_sq = sum(squared_deviations)
print(f"Шаг 4: сумма квадратов = {sum_sq}")

# Шаг 5: Разделить на (n-1) – выборочная дисперсия
variance_manual = sum_sq / (n - 1)
print(f"Шаг 5: выборочная дисперсия = {variance_manual}")

# Проверка через pandas
s = pd.Series(data)
print(f"Проверка .var(): {s.var()}")

# ==================================================
# Задание 1.2: Две команды с одинаковым средним, разной дисперсией
# ==================================================
print("\n=== Задание 1.2 ===")
np.random.seed(42)
# Команда A: стабильная (нормальное распределение, малое стандартное отклонение)
team_A = np.random.normal(loc=50, scale=5, size=8).round(1)
# Команда B: нестабильная (широкий разброс)
team_B = np.random.normal(loc=50, scale=20, size=8).round(1)

# Принудительно корректируем средние до одинакового значения (например, 50)
mean_A = team_A.mean()
mean_B = team_B.mean()
team_A_adj = team_A - mean_A + 50
team_B_adj = team_B - mean_B + 50

df_teams = pd.DataFrame({
    'Команда_A': team_A_adj,
    'Команда_B': team_B_adj
})
print("Данные команд:")
print(df_teams)
print(f"\nСреднее A: {df_teams['Команда_A'].mean():.2f}")
print(f"Среднее B: {df_teams['Команда_B'].mean():.2f}")
print(f"Дисперсия A: {df_teams['Команда_A'].var():.2f}")
print(f"Дисперсия B: {df_teams['Команда_B'].var():.2f}")

